def draw_shape(rng):
    """Deliberately includes very deep K. The cuBLAS split-K tail defect only appears there, and
    a sweep that never reaches it cannot support the claim "every mismatch is cuBLAS's own bug"
    -- it would simply never see one."""
    kind = rng.choice(["fp16", "fp16", "fp8"])
    regime = rng.choice(["square", "square", "thin", "deepk", "deepk", "decode"])
    if regime == "square":
        M, N, K = rng.randint(256, 8192), rng.randint(256, 16384), rng.randint(256, 16384)
    elif regime == "thin":
        M, N, K = rng.randint(16, 256), rng.randint(1024, 20000), rng.randint(1024, 20000)
    elif regime == "deepk":
        M, N, K = rng.randint(16, 512), rng.randint(64, 2048), rng.randint(20000, 300000)
    else:
        M, N, K = rng.randint(1, 64), rng.randint(1024, 16384), rng.randint(1024, 16384)
    if kind == "fp8":  # cuBLAS refuses fp8 unless every dimension is a multiple of 16
        M, N, K = (max(16, x // 16 * 16) for x in (M, N, K))
    elif rng.random() < 0.5:
        M, N, K = (max(16, x // 16 * 16) for x in (M, N, K))
    return M, N, K, kind


def cublas_drops_k_tail(torch, L, M, N, K, kind, out_dtype):
    """Is cuBLAS itself wrong on this shape?

    With A and B all ones every output must be exactly K. The known cuBLAS split-K defect returns
    the product over only the first `K - (K % block_k)` elements, so the output comes back as a
    smaller whole number. fp16 stops being able to represent consecutive integers above 2048, so
    the test is run in fp32 output where it is exact. Returns (is_wrong, observed, expected).
    """
    if kind == "fp8":
        return None, None, K  # the defect is an fp16/bf16 split-K path; fp8 never reaches it
    # The layouts are built here rather than through `_make_layouts` because the package only
    # describes fp16 and bf16 output to cuBLAS -- ask it for fp32 and it silently says fp16, and
    # reading the fp16 buffer as fp32 gives garbage. K reaches hundreds of thousands, which fp16
    # cannot even represent as an integer (it is exact only to 2048), so the output has to be
    # fp32 for the test to mean anything. This mirrors the standalone reproducer.
    lib = L._load_lt()
    a = torch.ones(M, K, device="cuda", dtype=torch.float16)
    b = torch.ones(K, N, device="cuda", dtype=torch.float16)
    c = torch.zeros(M, N, device="cuda", dtype=torch.float32)
    handle, desc, pref = ctypes.c_void_p(), ctypes.c_void_p(), ctypes.c_void_p()
    layouts = []
    try:
        L._ck("create", lib.cublasLtCreate(ctypes.byref(handle)))
        L._ck("desc", lib.cublasLtMatmulDescCreate(ctypes.byref(desc), L._CUBLAS_COMPUTE_32F, L._CUDA_R_32F))
        for rows, cols, dt in ((M, K, L._CUDA_R_16F), (K, N, L._CUDA_R_16F), (M, N, L._CUDA_R_32F)):
            lay = ctypes.c_void_p()
            L._ck("layout", lib.cublasLtMatrixLayoutCreate(ctypes.byref(lay), ctypes.c_int(dt),
                                                           ctypes.c_uint64(rows), ctypes.c_uint64(cols),
                                                           ctypes.c_int64(cols)))
            L._set_row(lib, lay)
            layouts.append(lay)
        la, lb, lc = layouts
        L._ck("pref", lib.cublasLtMatmulPreferenceCreate(ctypes.byref(pref)))
        ws = ctypes.c_size_t(L._workspace_bytes())
        L._ck("pref-set", lib.cublasLtMatmulPreferenceSetAttribute(pref, L._PREF_MAX_WS, ctypes.byref(ws), 8))
        wsbuf = L._ws_buffer(L._workspace_bytes())
        alpha, beta = ctypes.c_float(1.0), ctypes.c_float(0.0)
        rc = lib.cublasLtMatmul(handle, desc, ctypes.cast(ctypes.pointer(alpha), ctypes.c_void_p),
                                ctypes.c_void_p(a.data_ptr()), la, ctypes.c_void_p(b.data_ptr()), lb,
                                ctypes.cast(ctypes.pointer(beta), ctypes.c_void_p), ctypes.c_void_p(c.data_ptr()), lc,
                                ctypes.c_void_p(c.data_ptr()), lc, None, ctypes.c_void_p(wsbuf.data_ptr()),
                                ctypes.c_size_t(L._workspace_bytes()),
                                ctypes.c_void_p(torch.cuda.current_stream().cuda_stream))
        torch.cuda.synchronize()
        if rc != 0:
            return None, None, K
        v = float(c.flatten()[0].item())
    except Exception:
        return None, None, K
    finally:
        del a, b, c
        torch.cuda.empty_cache()
    return (abs(v - K) > 0.5), v, K


def step_bitmatch(args, env):
    import torch

    from bitequiv.cublas_match import cublas_equivalent_gemm, cublas_matmul
    from bitequiv.cublas_match import ltapi as L
    from bitequiv.cublas_match.errors import CublasUnsupportedShape

    out = writer("gemm.bitmatch")
    rng = random.Random(args.seed)
    deadline = time.time() + args.minutes * 60
    n = ok = declined = mism = 0
    print(f"\n[gemm.bitmatch] {args.minutes} min, {args.reps} input draws per shape, seed {args.seed}")
    while time.time() < deadline:
        M, N, K, kind = draw_shape(rng)
        esz = 1 if kind == "fp8" else 2
        if (M * K + K * N + M * N) * esz > args.max_bytes:
            continue
        seed = M * 1000003 + N * 10007 + K
        rec = {"M": M, "N": N, "K": K, "dtype": kind, "reps": args.reps}
        try:
            diffs = []
            for r in range(args.reps):
                a, b = make_inputs(torch, M, N, K, kind, r, seed)
                if r == 0:
                    from bitequiv.cublas_match.gemm import _resolve
                    from bitequiv.cublas_match.ltapi import _kind_of
                    rec["mode"] = _resolve(a, b, _kind_of(a), torch.float16).mode
                same = digest(torch, cublas_equivalent_gemm(a, b, torch.float16)) == digest(
                    torch, cublas_matmul(a, b, torch.float16))
                if not same:
                    diffs.append(r)
                del a, b
                torch.cuda.empty_cache()
            rec["n_differ"] = len(diffs)
            rec["draws_that_differ"] = diffs
            if diffs:
                mism += 1
                print(f"  MISMATCH  {kind} {M}x{N}x{K} mode={rec.get('mode')}  "
                      f"{len(diffs)}/{args.reps} draws differ", flush=True)
            else:
                ok += 1
            n += 1
        except CublasUnsupportedShape as e:
            declined += 1
            rec["declined"] = str(e)
        except Exception as e:
            rec["error"] = f"{type(e).__name__}: {e}"
        out.write(json.dumps(rec) + "\n")
        out.flush()
        torch.cuda.empty_cache()
    out.close()
    print(f"\n  {n} shapes x {args.reps} draws = {n * args.reps} comparisons")
    print(f"  byte-identical to cuBLAS      {ok}/{n}")
    print(f"  shapes with any differing draw {mism}   (logged in data/gemm.bitmatch.jsonl)")
    print(f"  declined (out of scope)       {declined}")
    if mism:
        print("  A mismatch is not automatically ours: cuBLAS itself drops the k tail on some\n"
              "  shapes -- run gemm.cublas-bug, which reproduces that defect on this machine.")


