PLAN_MODES = ("plain", "k_per_dot", "split", "split_blocks", "splitk_groups", "gemmsn", "gemv13", "gemv_cslice",
              "gemv14")


def _geo(xs):
    xs = [x for x in xs if x and x > 0]
    return round(math.exp(sum(map(math.log, xs)) / len(xs)), 4) if xs else None


def _f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def summarize():
    """Write data/summary.csv from the per-table CSVs in data/. Returns the row count."""
    import csv as _csv
    from collections import Counter, defaultdict
    out = []

    def add(exp, group, metric, value, n="", attempted="", note=""):
        if value is not None:
            out.append([exp, group, metric, value, n, attempted, note])

    def table(name):
        p = os.path.join(DATA, f"{name}.csv")
        return list(_csv.DictReader(open(p))) if os.path.exists(p) else []

    _summarize_bitmatch(table("gemm_bitmatch"), add, Counter)
    _summarize_perf(
        "gemm.perf.random", table("gemm_perf_random"), add, lambda r: (r["family"], r["dtype"], r["M"], r["N"], r["K"]),
        lambda k: f"{k[0]}/{k[1]}", 1400,
        "the full sweep at PERF_RANDOM_PER_CELL=100 is 1400 shapes; read run_perf_random.txt for "
        "the run's own coverage line before quoting a partial group")
    _summarize_perf("gemm.perf.static", table("gemm_perf_static"), add, lambda r:
                    (r["model"], r["layer"], r["pairing"], r["M"], r["N"], r["K"], r["dtype"]), lambda k: k[2], 698,
                    "698 (model, layer, dtype) cases over 590 distinct (M, N, K, dtype) shapes")
    _summarize_fusion(table("gemm_fusion"), add)
    _summarize_inner_tree(table("inner_tree_bitmatch"), table("inner_tree_layout"), add, defaultdict)
    _summarize_checker(table("checker_corpus"), add, Counter)
    _summarize_epilogue_swap(add)
    _summarize_cublas_bug(add)

    with open(os.path.join(DATA, "summary.csv"), "w", newline="") as fh:
        w = _csv.writer(fh)
        w.writerow(SUMMARY_COLS)
        w.writerows(out)
    return len(out)


def _summarize_bitmatch(rows, add, Counter):
    if not rows:
        return
    E = "gemm.bitmatch"
    cmpd = [r for r in rows if not r["declined"] and not r["error"]]
    diff = [r for r in cmpd if int(r["n_differ"] or 0) > 0]
    draws = sum(int(r["reps"] or 0) for r in cmpd)
    ddiff = sum(int(r["n_differ"] or 0) for r in cmpd)
    add(
        E, "all", "shapes_compared", len(cmpd), len(cmpd), len(rows),
        "this table is the UNION of every run, not one run. The runs behind this commit used "
        "different shape-regime code and are not comparable shape for shape")
    add(
        E, "all", "shapes_with_a_differing_draw", len(diff), len(cmpd), len(cmpd),
        "expected to be non-zero and to be entirely mode=split at deep K: that is cuBLAS's own "
        "k-tail defect, which gemm.cublas-bug reproduces standalone")
    add(E, "all", "draws_compared", draws, len(cmpd), len(cmpd))
    add(E, "all", "draws_byte_identical", draws - ddiff, len(cmpd), len(cmpd))
    add(E, "all", "shapes_declined", sum(1 for r in rows if r["declined"]), len(rows), len(rows),
        "out of scope, or cuBLAS returned no algorithm; no comparison was made")
    add(E, "all", "shapes_with_an_error", sum(1 for r in rows if r["error"]), len(rows), len(rows))
    by, bd = Counter(r["mode"] for r in cmpd), Counter(r["mode"] for r in diff)
    for m in PLAN_MODES:
        n = by.get(m, 0)
        add(E, f"mode={m}", "shapes_compared", n, n, n,
            "unreachable on sm_103: no arch profile lists a block-level key for it" if m == "split_blocks" else "")
        add(E, f"mode={m}", "shapes_with_a_differing_draw", bd.get(m, 0), n, n)


def _summarize_perf(exp, rows, add, keyf, groupf, planned, note):
    """The five-arm steps. Last write wins on (key, arm); a row with no baseline has no ratio."""
    if not rows:
        return
    by = {}
    for r in rows:
        by.setdefault(keyf(r), {})[r["arm"]] = r
    groups = {"all": list(by.values())}
    for k, arms in by.items():
        groups.setdefault(groupf(k), []).append(arms)
    for g in sorted(groups, key=lambda x: (x != "all", x)):
        cases = groups[g]
        partial = g == "all" and planned and len(cases) < planned
        add(exp, g, "shapes_measured", len(cases), len(cases), planned if g == "all" else len(cases),
            ("PARTIAL. " if partial else "") + (note if g == "all" else ""))
        for a in ("torch_auto", "torch_triton", "pre_search", "ours"):
            v = [
                _f((c.get("cublas") or {}).get("device_flush_ms")) / _f((c.get(a) or {}).get("device_flush_ms"))
                for c in cases
                if _f((c.get("cublas") or {}).get("device_flush_ms")) and _f((c.get(a) or {}).get("device_flush_ms"))
            ]
            add(
                exp, g, f"{ARM_PUBLIC[a]}_over_cublas_geomean", _geo(v), len(v), len(cases),
                "device_flush_ms, cuBLAS over this arm, so above 1 is faster than cuBLAS. "
                "near_floor rows are included, as everywhere in this artifact")
        for a in ("ours", "pre_search", "torch_auto"):
            ok = sum(int((c.get(a) or {}).get("bit_ok") or 0) for c in cases)
            tot = sum(int((c.get(a) or {}).get("bit_total") or 0) for c in cases)
            if tot:
                add(
                    exp, g, f"{ARM_PUBLIC[a]}_draws_byte_identical", ok, tot, tot,
                    "unconstrained arm, not expected to match" if a == "torch_auto" else
                    "MUST equal the total: this arm is bit-equivalent to cuBLAS by construction, "
                    "and a short count means its times are not a measurement")
        add(exp, g, "shapes_with_a_near_floor_arm",
            sum(1 for c in cases if any((c.get(a) or {}).get("near_floor") == "1" for a in ARM_PUBLIC)), len(cases),
            len(cases), "under three times the replay floor, so every ratio on them is pulled toward 1")


def _summarize_fusion(rows, add):
    if not rows:
        return
    E, ARMS = "gemm.fusion", ("torch_fused", "bitequiv_autotuner_fused", "gb300_fused")
    seen = {}
    for r in rows:
        seen[(r["model"], r["layer"], r["M"], r["N"], r["K"], r["dtype"])] = r
    good = [r for r in seen.values() if _f(r["cublas_unfused_ms"])]
    groups = [("all", lambda r: True)]
    for field, label in (("mode", "mode"), ("dtype", "dtype"), ("pairing", "layer"), ("epi", "epilogue")):
        for v in sorted({r[field] for r in good if r[field]}):
            groups.append((f"{label}={v}", (lambda f, v: lambda r: r[f] == v)(field, v)))
    groups.append(("above_the_replay_floor", lambda r: r["near_floor"] != "1"))
    for gname, sel in groups:
        sub = [r for r in good if sel(r)]
        if not sub:
            continue
        add(E, gname, "rows_measured", len(sub), len(sub), len(sub),
            "48 selected cases at fp16 and bf16, out of 405 reachable model cases" if gname == "all" else "")
        for a in ARMS:
            add(E, gname, f"{a}_over_cublas_unfused_geomean", _geo([_f(r[f"{a}_over_cublas_unfused"]) for r in sub]),
                len(sub), len(sub), "above 1 is faster than cuBLAS plus a separate epilogue kernel")
            add(E, gname, f"{a}_rows_beating_the_baseline",
                sum(1 for r in sub if (_f(r[f"{a}_over_cublas_unfused"]) or 0) > 1), len(sub), len(sub))
        tot = sum(int(r["bit_total"] or 0) for r in sub)
        for a in ARMS:
            add(
                E, gname, f"{a}_draws_byte_identical", sum(int(r[f"{a}_bit_ok"] or 0) for r in sub), tot, tot,
                "unconstrained arm, not expected to match"
                if a == "torch_fused" else "MUST equal the total: this arm is bit-exact by construction")


def _summarize_inner_tree(bit_rows, lay_rows, add, defaultdict):
    if bit_rows:
        E = "inner_tree.bitmatch"
        seen = {}
        for r in bit_rows:
            seen[(r["kernel"], r["dtype"], r["enable_fp_fusion"], r["ordering"])] = r
        u = list(seen.values())
        real = [r for r in u if r["control"] != "1"]
        ctl = [r for r in u if r["control"] == "1"]
        it = [r for r in real if r["ordering"] == "inner_tree"]
        ev = [r for r in it if r["sensitive"] == "1"]
        add(E, "all", "cells_measured", len(u), len(u), len(u),
            f"{len(real)} real and {len(ctl)} control, 36 configurations swept inside each")
        add(E, "all", "inner_tree_cells", len(it), len(it), len(it))
        add(
            E, "all", "inner_tree_cells_with_a_sensitive_partner", len(ev), len(it), len(it),
            "the matching unordered cell returned more than one byte pattern, so the sweep did "
            "move the bits on that kernel and an invariant inner_tree cell means something")
        add(
            E, "all", "inner_tree_cells_NOT_invariant", sum(1 for r in ev if r["invariant"] != "1"), len(ev), len(ev),
            "MUST be 0; this is the claim. Non-zero on this tree and correctly so: "
            "D_masked_global_sum at f32, at both enable_fp_fusion settings, returns three byte "
            "classes split by num_warps. A real counterexample, not a broken artifact")
        add(
            E, "all", "inner_tree_cells_with_no_evidence", sum(1 for r in it if r["sensitive"] == "0"), len(it),
            len(it), "the unordered arm did not differ either, so these prove nothing in either "
            "direction. All of them are fp8 pure sums, order-invariant by arithmetic: untested, not passing")
        add(
            E, "all", "controls_not_invariant", sum(1 for r in ctl if r["invariant"] != "1"), len(ctl), len(ctl),
            "MUST be 0: a max reduction is order-invariant by operation, so a control that moves "
            "means the harness is broken rather than the mode")
        add(E, "all", "configurations_compiled_and_launched", sum(int(r["n_ran"] or 0) for r in u), len(u), len(u))
        add(E, "all", "configurations_that_failed_to_build", sum(int(r["n_failed"] or 0) for r in u), len(u), len(u))
    if lay_rows:
        E, n = "inner_tree.layout", len(lay_rows)
        add(E, "all", "rows_measured", n, n, n, "17 kernels over 24 (kernel, dtype) pairs x 72 configurations")
        add(E, "all", "bit_changed_configurations", sum(1 for r in lay_rows if r["bit_changed"] == "1"), n, n,
            "MUST be 0; the hard gate. A speedup on a row whose bytes moved is not a result")
        add(E, "all", "bit_changed_on_the_perf_input", sum(1 for r in lay_rows if r["bit_identical_perf"] == "0"), n, n,
            "MUST be 0; an independent second comparison on the timing arm's own input")
        add(
            E, "all", "compile_regressions", sum(1 for r in lay_rows if r["compile_regression"] == "1"), n, n,
            "the baseline built and the optimized build died in ptxas. Non-zero on this tree and "
            "correctly so: all 12 are sum_2d_col_big f16 num_warps=4, sitting exactly on the "
            "register-pressure guard's boundary. A real bug in the pass; it makes the run a FAIL")
        add(E, "all", "order_insensitive_rows", sum(1 for r in lay_rows if r["order_sensitive"] == "0"), n, n,
            "the reduction does not depend on the order here, so bit_changed = 0 is vacuous, not a pass")
        fired = [r for r in lay_rows if _f(r["speedup"]) and r["pass_changed_ir"] == "1"]
        add(
            E, "all", "speedup_geomean_where_the_pass_fired", _geo([_f(r["speedup"]) for r in fired]), len(fired), n,
            "baseline_ms / optimized_ms on the rows the pass actually rewrote. Seven of the 24 "
            "(kernel, dtype) pairs have no row below at all because the pass declined every "
            "configuration on them, which is a guard working rather than a gap")
        per = defaultdict(list)
        for r in fired:
            per[f"{r['kernel']}/{r['dtype']}"].append(_f(r["speedup"]))
        for k in sorted(per):
            add(E, k, "speedup_geomean_where_the_pass_fired", _geo(per[k]), len(per[k]), 72)


def _summarize_checker(rows, add, Counter):
    if not rows:
        return
    E = "checker.corpus"
    tot = [r for r in rows if r["scope"] == "total" and r["cap"] == "0"]
    grp = [r for r in rows if r["scope"] == "group" and r["cap"] == "0"]
    for r in tot:
        g, n = r["kernel"], int(r["configs"])
        add(E, g, "configurations_graded", n, n, n, r["notes"])
        add(E, g, "checker_classes", int(r["checker_cls"]), n, n,
            "equivalence classes the checker proved; fewer is more tuning freedom recovered")
        add(E, g, "empirical_classes", int(r["empirical_cls"]), n, n,
            "classes the recorded output bytes actually fall into")
        add(
            E, g, "over_merges", int(r["over_merges"]), n, n,
            "MUST be 0; the only hard gate here. Above 0 means the checker called two "
            "configurations equal and the hardware disagreed, which is a soundness bug")
        add(E, g, "over_splits", int(r["over_splits"]), n, n,
            "tuning freedom given up to stay safe: a trade-off, not a failure")
    add(
        E, "all", "groups_graded", len(grp), len(grp), len(grp),
        "the three totals above cover fewer than this: a group that graded 0 configurations is "
        "dropped from them rather than counted as a clean 0")
    for k, v in sorted(Counter(r["recovery"] for r in grp).items()):
        add(
            E, "all", f"groups_with_recovery={k}", v, len(grp), len(grp),
            "every configuration in its own class: the checker refusing to answer rather than "
            "answering wrongly" if k == "fail-closed" else "")


def _summarize_epilogue_swap(add):
    """The one measurement where the bit constraint is isolated. Not one of the steps."""
    src = os.path.join(HERE, "fusion_oracle", "three_way.jsonl")
    if not os.path.exists(src):
        return
    E, TAG = "epilogue_swap", "oracle2"
    merged = {}
    for line in open(src):
        line = line.strip()
        if not line:
            continue
        try:
            r = json.loads(line)
        except Exception:
            continue
        if r.get("tag") == TAG:
            merged[(r["M"], r["N"], r["K"], r["epi"], r.get("params_tag", ""))] = r
    recs = list(merged.values())
    if not recs:
        return

    def ms(r, a):
        return (r.get(a) or {}).get("ms")

    won = [r for r in recs if ms(r, "triton") and ms(r, "exact2k") and ms(r, "exact2k") > ms(r, "triton")]
    usable = [r for r in won if ms(r, "ours") and (r.get("ours") or {}).get("bit_exact")]
    add(
        E, TAG, "cases_measured", len(recs), len(recs), len(recs),
        "NOT one of the eight steps, and the ONLY measurement in this artifact where the bit "
        "constraint is isolated: the unconstrained arm is the kernel torch.compile emitted, and "
        "the bit-exact arm is THAT SAME SOURCE with only the epilogue arithmetic swapped -- same "
        "mainloop, tile, grid and launch. Reproduce with `python fusion_oracle/report.py oracle2`; no GPU needed")
    add(E, TAG, "cases_where_fusing_beat_the_two_kernel_baseline", len(won), len(recs), len(recs),
        "a case counts only if fusing was already a win; otherwise there is nothing to ask about")
    add(E, TAG, "cases_byte_identical_after_the_swap", sum(1 for r in recs if (r.get("ours") or {}).get("bit_exact")),
        len(recs), len(recs))
    add(
        E, TAG, "unconstrained_over_bit_exact_geomean", _geo([ms(r, "triton") / ms(r, "ours") for r in usable]),
        len(usable), len(recs), "THE cost of bit-exactness, and the only number in this artifact allowed that label. "
        "Below 1 means the bit-exact spelling is slower: 0.936 is a 6.4% gap")
    add(E, TAG, "bit_exact_fused_over_cublas_unfused_geomean", _geo([ms(r, "exact2k") / ms(r, "ours") for r in usable]),
        len(usable), len(recs), "the same bit-exact kernel against the two-kernel path a determinism user has today")


