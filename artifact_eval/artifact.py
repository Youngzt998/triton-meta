def step_fusion(args, env):
    """PLACEHOLDER -- the design is settled, the code is not written yet.

    Question: for an epilogue cuBLAS cannot fuse, how much faster is our bit-exact GEMM with the
    epilogue folded in than the two-kernel path a user gets today?

    Three arms, same shapes, same inputs, device time by CUDA-graph replay:
      1. cuBLAS through a hot closure, then the epilogue as its own Triton kernel. This is the
         baseline a user actually gets. Note it is TWO kernels even for a four-op chain, because
         Inductor fuses a pointwise chain into one kernel even when it cannot fuse into the GEMM.
      2. Ours: the bit-exact GEMM with the epilogue applied to the accumulator before the store.
         It must be BYTE-IDENTICAL to arm 1, which means rounding to the output dtype at the op
         boundary exactly where the unfused version rounds -- what Inductor calls "emulate
         unfused numerics". If it is not byte-identical the timing is meaningless.
      3. The same fusion on an unconstrained autotuned Triton matmul: the ceiling, and what
         torch.compile with max-autotune would pick. arm2/arm3 is the price of the constraint.

    Epilogues must be ones cuBLASLt cannot express -- its whole list is bias, relu, gelu and
    their backward and bias-gradient variants. So: silu, a two-tensor gate `x * sigmoid(g)`,
    `(x + residual) * scale`, and a four-op chain.

    Report per shape as well as a geometric mean, because the win grows as K shrinks and that
    trend matters more than one number.
    """
