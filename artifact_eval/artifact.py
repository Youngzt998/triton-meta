# The head of data/FORMAT.md. It carries the RULES FOR RECOMPUTING A TABLE, not just the column
# meanings: the CSVs are append logs and every step's report filters and de-duplicates them before
# it averages anything. Somebody who reads a CSV without those rules gets different numbers and no
# way to tell why, so they belong next to the columns rather than in a step's source.
FORMAT_PREAMBLE = """\
# Data format

One CSV per experiment, first line is the header. Generated by `artifact.py --export` from the
streaming records in `cache/`. An empty cell means the field does not apply to that row.

`cache/` itself is live and is not committed; the frozen copy of it is `data/records/`, the same
records gzipped, one file per table. Unpack those back into `cache/` and `--export` regenerates
every CSV here exactly -- `data/records/README.md` has the commands, the row counts, and what each
file is. Read a record when a CSV column is not enough: the records are what these tables are
computed from.

`env.csv` records the machine each run was taken on. Which kernel cuBLAS picks -- and therefore
the bits it returns -- depends on the architecture and the cuBLASLt version, so a row is only
comparable to another row with the same two.

## How to get the same numbers back out

**These files are append logs, not tables.** Every record a step ever wrote is in them, including
records a later run replaced. A step's own report applies the four rules below before it averages
anything, and a reader who skips them will compute different numbers from the same file.

1. **Last write wins.** Most tables are de-duplicated on a key before anything is averaged, and
   only the most recent record for a key survives:

   | table | key |
   |---|---|
   | `gemm_perf_random` | `(family, dtype, M, N, K, arm)` |
   | `gemm_perf_static` | `(model, layer, pairing, M, N, K, dtype, arm)` |
   | `gemm_fusion` | `(model, layer, M, N, K, dtype)` |
   | `inner_tree_bitmatch` | `(kernel, dtype, enable_fp_fusion, ordering)` |
   | `checker_corpus` | `(corpus, cap, checker, kernel, dtype)` |

   Two tables are **not** de-duplicated, for opposite reasons. `inner_tree_layout` does not need
   it: a run refuses to re-measure a `(kernel, dtype, configuration)` it already holds, so the
   file has exactly one row each. `gemm_bitmatch` does not do it on purpose: the file is the union
   of every run, and the runs behind this commit used different shape-regime code, so it is not
   comparable shape for shape across them. Read one run's report, not the union, unless you mean
   the union.

   `checker_corpus` also carries rows at more than one `cap`. **Filter on `cap` first.** A capped
   row is a strided sample of its group, not the group. In this commit 93 rows are at `cap = 0`
   and 4 more are a `cap = 48` sample of four of the same groups.

2. **A row with no baseline time has no ratio.** Where `declined` or `error` is non-empty, or the
   baseline arm has no time, that row contributes nothing to any mean. It is counted and named in
   the report instead of being dropped silently. This is why the number of rows in a CSV is larger
   than the `n` printed beside a geometric mean.

3. **`near_floor` rows stay in.** A row flagged `near_floor = 1` -- its time is under three times
   `floor_ms`, so it is mostly launch overhead and its ratio is pulled toward 1 -- is **kept** in
   the headline geometric means and reported as a separate count. `gemm.fusion` additionally
   prints an `above the replay floor` group with those rows removed, so the same file supports two
   different aggregate numbers and you have to say which one you mean.

4. **Aggregates are geometric means of per-row ratios**, never a ratio of summed times, and every
   ratio is oriented `baseline_time / arm_time`, so **above 1 means faster than the baseline**.
   The baseline is the `cublas` arm for `gemm_perf_random` and `gemm_perf_static`, and
   `cublas_unfused` for `gemm_fusion`. No table reports a ratio between two non-baseline arms.

One more thing that is in the data but easy to miss: `batch_n` is how many calls went into one
CUDA graph, each on its own operand copy, with the replay divided by that. A row with an empty
`batch_n` was taken before batching existed and on a small shape it is **not** comparable with a
batched row -- it reads slower.

`summary.csv` is derived from the per-table CSVs above by the same `--export`, using exactly the
four rules just stated. Its own section at the end of this file says what each of its rows means.
"""

SUMMARY_DOC = """
## summary.csv

The headline numbers, one row per (experiment, group, metric). Long format on purpose: a wide
table of every metric every experiment produces is mostly empty cells, and an empty cell reads as
a zero to somebody skimming.

`--export` writes it last, from the per-table CSVs it has just written, using the four rules in
*How to get the same numbers back out* -- so every value in it can be recomputed from what ships,
and it cannot drift away from the tables it came from. Where a run was partial, the row says so in
`n` against `attempted` and in `note` rather than being left out: a partial sweep and a complete
one look the same once averaged, and only the counts tell them apart.

| column | type | meaning |
|---|---|---|
| `experiment` | str | the step the number comes from, or `epilogue_swap` for the one measurement that is not a step |
| `group` | str | the slice within that step: `all`, a cuBLAS plan mode, a layer group, a dtype, an arm |
| `metric` | str | what `value` is. A metric ending `_over_cublas_geomean` or `_over_cublas_unfused_geomean` is a geometric mean of per-row baseline-time-over-arm-time ratios, so above 1 is faster than the baseline |
| `value` | float | the number |
| `n` | int | rows, cases or shapes actually behind `value` |
| `attempted` | int | how many there would be at full coverage; equal to `n` when the group is complete |
| `note` | str | anything a reader needs before quoting the row, including why it is partial |
"""

